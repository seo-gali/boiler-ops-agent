@lru_cache(maxsize=64)
def image_dimensions(path):
    """문서 JPEG의 프레임 크기만 읽어 원본 비율 보존."""
    with path.open('rb') as source:
        if source.read(2) != b'\xff\xd8':
            raise ValueError(f'Expected a JPEG document image: {path.name}')
        while source.read(1) == b'\xff':
            marker = source.read(1)
            while marker == b'\xff':
                marker = source.read(1)
            if not marker or marker[0] in (0xda, 0xd9):
                break
            length = int.from_bytes(source.read(2), 'big')
            if length < 2:
                break
            if 0xc0 <= marker[0] <= 0xcf and marker[0] not in (0xc4, 0xc8, 0xcc):
                frame = source.read(5)
                if len(frame) == 5:
                    return int.from_bytes(frame[3:5], 'big'), int.from_bytes(frame[1:3], 'big')
                break
            source.seek(length - 2, 1)
    raise ValueError(f'JPEG frame dimensions not found: {path.name}')


def inline(text, source):
    escaped = html.escape(text)
    tokens = []

    def keep(value):
        tokens.append(value)
        return f'\x00{len(tokens) - 1}\x00'

    escaped = re.sub(r'`([^`]+)`', lambda m: keep('<code>' + m[1] + '</code>'), escaped)

    def link(match):
        image, label, target = match.groups()
        target = html.unescape(target).split('#')[0]
        if target.startswith(('https://', 'http://')):
            return keep(f'<a href="{html.escape(target, quote=True)}" target="_blank" rel="noreferrer">{label} (새 탭)</a>')
        path = (ROOT / source).parent / target
        try:
            relative = path.resolve().relative_to(ROOT).as_posix()
        except ValueError:
            return label
        if image and relative.startswith('docs/images/') and path.is_file():
            width, height = image_dimensions(path)
            return keep(f'<img src="{html.escape(relative[5:], quote=True)}" alt="{label}" width="{width}" height="{height}" loading="lazy" decoding="async">')
        if relative in FILES:
            return keep(f'<button data-doc="{html.escape(relative, quote=True)}">{label}</button>')
        return label

    escaped = re.sub(r'(!?)\[([^\]]+)\]\(([^)]+)\)', link, escaped)
    escaped = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', escaped)
    escaped = re.sub(r'\x00(\d+)\x00', lambda m: tokens[int(m[1])], escaped)
    return escaped


def markdown(text, source):
    lines = text.splitlines()
    output, paragraph = [], []
    i = 0

    def flush():
        if paragraph:
            output.append('<p>' + inline(' '.join(paragraph), source) + '</p>')
            paragraph.clear()

    while i < len(lines):
        line = lines[i]
        if line.startswith('```'):
            flush()
            code = []
            i += 1
            while i < len(lines) and not lines[i].startswith('```'):
                code.append(lines[i])
                i += 1
            output.append('<pre><code>' + html.escape('\n'.join(code)) + '</code></pre>')
        elif line.startswith('|') and i + 1 < len(lines) and re.match(r'^\|[\s:|\-]+\|?$', lines[i + 1]):
            flush()
            cells = lambda row: row.strip().strip('|').split('|')
            output.append('<table><thead><tr>' + ''.join('<th scope="col">' + inline(cell.strip(), source) + '</th>' for cell in cells(line)) + '</tr></thead><tbody>')
            i += 2
            while i < len(lines) and lines[i].startswith('|'):
                output.append('<tr>' + ''.join('<td>' + inline(cell.strip(), source) + '</td>' for cell in cells(lines[i])) + '</tr>')
                i += 1
            output.append('</tbody></table>')
            continue
        elif heading := re.match(r'^(#{1,6})\s+(.*)', line):
            flush()
            level = min(len(heading[1]), 3)
            output.append(f'<h{level}>' + inline(heading[2], source) + f'</h{level}>')
        elif re.match(r'^\s*(?:[-*]|\d+\.)\s+', line):
            flush()
            ordered = bool(re.match(r'^\d+\.', line))
            tag = 'ol' if ordered else 'ul'
            output.append(f'<{tag}>')
            while i < len(lines) and re.match(r'^\s*(?:[-*]|\d+\.)\s+', lines[i]):
                content = re.sub(r'^\s*(?:[-*]|\d+\.)\s+', '', lines[i])
                output.append('<li>' + inline(content, source) + '</li>')
                i += 1
            output.append(f'</{tag}>')
            continue
        elif not line.strip() or line.strip() == '---':
            flush()
        else:
            paragraph.append(line)
        i += 1
    flush()
    return '\n'.join(output)


def document_url(name):
    return 'read/' + name.removesuffix('.md').replace('/', '-').replace('_', '-').lstrip('.').lower() + '.html'


def feature_panels():
    features = json.loads((ROOT / 'docs/feature-data.json').read_text(encoding='utf-8'))
    panels = []
    for name, feature in features.items():
        button = lambda path, label, css='': f'<button class="{css}" data-doc="{html.escape(path, quote=True)}">{html.escape(label)}</button>'
        flow = ''.join('<li><b>' + html.escape(label) + '</b><small>' + html.escape(sub) + '</small>' + button(path, file + ' ↗', 'file-button') + '</li>' for label, sub, path, file in feature['steps'])
        contracts = ''.join('<code>' + html.escape(line) + '</code>' for line in feature['contract'])
        sources = ''.join(button(path, Path(path).name + ' ↗') for path in feature['sources'])
        report = button(feature['report'], feature['reportLabel'], 'action') if feature.get('report') else ''
        panels.append(f'<section class="feature-panel" data-feature-panel="{html.escape(name, quote=True)}"' + ('' if name == 'telemetry' else ' hidden') + '><h3>' + html.escape(feature['title']) + '</h3><p>' + html.escape(feature['description']) + '</p><ol class="flow">' + flow + '</ol><details class="contracts"><summary>타입·시그니처·호출 계약 펼치기</summary>' + contracts + '</details><div class="details-line">' + sources + '</div>' + report + '</section>')
    return '\n'.join(panels)


def publish_documents(content):
    documents = {name: document_url(name) for name in FILES if name.endswith('.md')}
    if len(set(documents.values())) != len(documents):
        raise ValueError('Duplicate public document URLs')
    folder = ROOT / 'docs/read'
    folder.mkdir(exist_ok=True)
    for name, relative in documents.items():
        def link(match):
            target, label = html.unescape(match[1]), match[2]
            if target in documents:
                destination = Path(documents[target]).name
            elif target.startswith('docs/'):
                destination = '../' + target[5:]
            else:
                destination = 'https://github.com/seo-gali/boiler-ops-agent/blob/main/' + quote(target)
            return f'<a href="{html.escape(destination, quote=True)}">{label}</a>'

        rendered = re.sub(r'<button data-doc="([^"]+)">(.*?)</button>', link, content[name]['html'], flags=re.DOTALL)
        rendered = rendered.replace('src="images/', 'src="../images/')
        description = ' '.join(html.unescape(re.sub(r'<[^>]+>', ' ', rendered)).split())[:180]
        title = html.escape(content[name]['title'])
        page = f'''<!doctype html>
{GENERATED}
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · BoilerOps Agent</title><meta name="description" content="{html.escape(description, quote=True)}">
<meta name="robots" content="index,follow"><link rel="canonical" href="{SITE + relative}">
<link rel="icon" href="../favicon.svg" type="image/svg+xml"><link rel="stylesheet" href="../fonts/pretendard.css"><link rel="stylesheet" href="../brand.css"><link rel="stylesheet" href="../guide.css"></head>
<body><a class="skip" href="#main">본문으로 건너뛰기</a><header><div class="bar"><a class="brand" href="../">BoilerOps Agent · 프로젝트 지도</a></div></header>
<main id="main" class="reader-body" style="max-width:980px;margin:auto"><p class="reader-path">{html.escape(name)}</p>{rendered}</main></body></html>
'''
        (ROOT / 'docs' / relative).write_text(page, encoding='utf-8')
    for path in folder.glob('*.html'):
        if path.name not in {Path(name).name for name in documents.values()} and GENERATED in path.read_text(encoding='utf-8')[:200]:
            path.unlink()
    namespace = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', namespace)
    sitemap = ET.Element(f'{{{namespace}}}urlset')
    for url in [SITE, *(SITE + path for path in documents.values())]:
        ET.SubElement(ET.SubElement(sitemap, f'{{{namespace}}}url'), f'{{{namespace}}}loc').text = url
    ET.indent(sitemap)
    ET.ElementTree(sitemap).write(ROOT / 'docs/sitemap.xml', encoding='utf-8', xml_declaration=True)
    (ROOT / 'docs/robots.txt').write_text('# Google reads this policy only at https://seo-gali.github.io/robots.txt\nUser-agent: *\nAllow: /\nSitemap: ' + SITE + 'sitemap.xml\n', encoding='utf-8')
    shutil.copyfile(ROOT / 'frontend/public/favicon.svg', ROOT / 'docs/favicon.svg')
    return '<ul>' + ''.join(f'<li><a href="{url}">{html.escape(content[name]["title"])}</a></li>' for name, url in documents.items()) + '</ul>'


def main():
    content = {}
    for name in FILES:
        text = (ROOT / name).read_text(encoding='utf-8')
        title = text.splitlines()[0].lstrip('# ') if name.endswith('.md') else Path(name).name
        rendered = markdown(text, name) if name.endswith('.md') else '<pre><code>' + html.escape(text) + '</code></pre>'
        content[name] = {'title': title, 'html': rendered}
    payload = json.dumps(content, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
    target = ROOT / 'docs/index.html'
    page, count = re.subn(r'<script id="guide-content">.*?</script>',
                          lambda _: '<script id="guide-content">\nwindow.guideContent=' + payload + ';\n</script>',
                          target.read_text(encoding='utf-8'), flags=re.DOTALL)
    if count != 1:
        raise ValueError('Expected exactly one guide-content block in docs/index.html')
    catalog = publish_documents(content)
    for label, markup in [('feature-panels', feature_panels()), ('document-links', catalog)]:
        page, count = re.subn(f'<!-- {label}:start -->.*?<!-- {label}:end -->', lambda _: f'<!-- {label}:start -->\n{markup}\n<!-- {label}:end -->', page, flags=re.DOTALL)
        if count != 1:
            raise ValueError(f'Expected exactly one {label} block')

    def size_image(match):
        attributes = re.sub(r'\s+(?:width|height|decoding)="[^"]*"', '', match[1])
        width, height = image_dimensions(ROOT / 'docs' / match[2])
        return f'<img{attributes} width="{width}" height="{height}" decoding="async">'

    page = re.sub(r'<img\b([^>]*\bsrc="(images/[^"]+)"[^>]*)>', size_image, page)
    target.write_text(page, encoding='utf-8')
    print(f'Built {len(content)} offline document/source previews')


if __name__ == '__main__':
    main()
