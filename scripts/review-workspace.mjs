import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { inspect } from './review-ui.mjs';

export async function reviewWorkspace({ page, context, apiFetch, base, out, root, profile, poll, pass }) {
  const json = async path => { const response = await apiFetch(base + path); assert.equal(response.status, 200); return response.json(); };
  const registry = await json('/api/registry');
  const definitions = JSON.parse(readFileSync(resolve(root, 'backend/app/domain/sensor_definitions.json'), 'utf8'));
  assert.equal(definitions.source_sha256, createHash('sha256').update(readFileSync(resolve(root, 'data/raw/CustomExcelView.xlsx'))).digest('hex'));
  assert.equal(definitions.dataset_sha256, profile.sha256);
  assert.equal(Object.keys(definitions.sensors).length, 118);
  for (const [tag, definition] of Object.entries(definitions.sensors)) {
    assert.equal(registry.sensors[tag].unit, definition.unit, tag);
    assert.ok(registry.sensors[tag].unit_basis.includes(String(definition.source_row)));
  }
  const kpiUnits = await page.locator('.kpi small').allTextContents();
  assert.deepEqual(kpiUnits, ['MW', 'MW', 'T/H', 'kg/cm2g', '°C', '%']);
  pass('118 source tags and workbook hash match registry units; all six KPI units are visible');
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.evaluate(() => document.fonts.check('16px "Pretendard Variable"')), true);
  assert.match(await page.locator('body').evaluate(node => getComputedStyle(node).fontFamily), /Pretendard/);
  const requests = [];
  page.on('request', request => { if (/\/api\/(agent\/query|simulator\/proposals)$/.test(new URL(request.url()).pathname)) requests.push(request.url()); });
  const downloads = []; page.on('download', item => downloads.push(item.suggestedFilename()));
  const initialPages = context.pages().length;
  await page.getByRole('button', { name: '화면 자동 갱신 일시정지', exact: true }).click();
  const scene = page.getByLabel('계통도 화면', { exact: true });
  const drawer = page.getByRole('complementary', { name: '운전 도우미' });
  const selected = () => page.getByLabel('선택 센서', { exact: true }).inputValue();
  await page.setViewportSize({ width: 1800, height: 1100 });
  for (const [index, item] of registry.equipment.entries()) {
    await page.getByRole('button', { name: `${String(index + 1).padStart(2, '0')} ${item.name}`, exact: true }).click();
    assert.equal(await selected(), item.primary_tag);
    await page.getByRole('tab', { name: '센서 상세', exact: true }).click();
    assert.equal(await page.getByTestId('inspector-tag').textContent(), item.primary_tag);
    assert.ok((await drawer.textContent()).includes(item.description));
    const marker = page.getByTestId(`marker-${item.primary_tag}`);
    await marker.click();
    const markerBox = await marker.boundingBox(), sceneBox = await scene.boundingBox();
    assert.ok(markerBox.y >= sceneBox.y && markerBox.y + markerBox.height <= sceneBox.y + sceneBox.height, `${item.name} label is fully inside the scene`);
    assert.equal(await marker.getAttribute('aria-pressed'), 'true');
    assert.ok((await marker.textContent()).includes(await page.getByTestId('inspector-value').textContent()));
  }
  pass('All seven equipment buttons and visible markers select the same named primary sensor and value');
  await page.getByRole('button', { name: '도우미 닫기' }).click();
  await scene.scrollIntoViewIfNeeded(); await scene.focus();
  const marker = page.getByTestId(`marker-${registry.equipment[2].primary_tag}`);
  const before = await marker.boundingBox(); const box = await scene.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.keyboard.down('Space');
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 55, box.y + box.height / 2 + 28, { steps: 8 }); await page.mouse.up();
  await poll(async () => { const after = await marker.boundingBox(); return after.x > before.x + 35 && after.y > before.y + 15; }, 'Space drag pans in both axes');
  const scrollBefore = await page.evaluate(() => scrollY);
  await page.mouse.wheel(0, -180);
  await poll(async () => parseInt(await page.getByLabel('계통도 확대 비율').textContent()) > 100, 'Space wheel zoom');
  assert.equal(await page.evaluate(() => scrollY), scrollBefore);
  await page.keyboard.up('Space');
  await page.mouse.wheel(0, 180);
  await poll(async () => await page.evaluate(() => scrollY) > scrollBefore, 'Normal wheel scroll restored');
  await scene.scrollIntoViewIfNeeded(); await scene.focus();
  await page.keyboard.down('Space');
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  assert.equal(await page.locator('.scene-mode').textContent(), '');
  await page.keyboard.up('Space');
  await page.keyboard.down('Space');
  await scene.dispatchEvent('pointercancel');
  assert.equal(await page.locator('.scene-mode').textContent(), '');
  await page.keyboard.up('Space');
  await page.getByRole('button', { name: '보기 초기화', exact: true }).click();
  assert.equal(await page.getByLabel('계통도 확대 비율').textContent(), '100%');
  await marker.click(); assert.equal(await selected(), registry.equipment[2].primary_tag);
  pass('Space drag pans both axes and wheel zooms; key release restores scroll; blur/pointercancel exit pan; reset and click recover');

  // 도형 표면 클릭과 기본 센서 선택
  await page.getByRole('button', { name: '도우미 닫기' }).click();
  await scene.scrollIntoViewIfNeeded();
  for (const item of registry.equipment) {
    const label = page.getByTestId(`marker-${item.primary_tag}`);
    await label.waitFor({ state: 'visible' });
    await label.click({ trial: true });
    const target = await label.boundingBox();
    await page.mouse.click(target.x + target.width / 2, target.y + target.height + 32);
    await poll(async () => await selected() === item.primary_tag, `Mesh hit for ${item.id}`);
    await page.getByRole('button', { name: '도우미 닫기' }).click();
    await scene.scrollIntoViewIfNeeded();
  }
  assert.equal(requests.length, 0, 'Selection and navigation must not invoke AI or create proposals');
  pass('Visible surfaces of all seven meshes select their primary sensor; selection makes no model or write request');

  await page.getByRole('button', { name: 'AI 도우미 열기' }).click();
  await page.getByRole('tab', { name: '변경 기록', exact: true }).click();
  await page.getByText('아직 승인·변경 기록이 없습니다.', { exact: false }).waitFor();
  await page.getByRole('tab', { name: 'AI 질문', exact: true }).click();
  await page.getByLabel('선택 센서', { exact: true }).selectOption(registry.equipment[3].primary_tag);
  await page.getByLabel('질문', { exact: true }).fill('선택한 센서의 현재값은?');
  await page.getByLabel('질문', { exact: true }).press('End'); await page.keyboard.press('Space');
  assert.match(await page.getByLabel('질문', { exact: true }).inputValue(), / $/);
  await page.getByRole('tab', { name: '승인 연습', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Agent Simulator 제안 생성', exact: true }).isDisabled(), true);
  await page.getByRole('tab', { name: 'AI 질문', exact: true }).click();
  assert.match(await page.getByLabel('질문', { exact: true }).inputValue(), / $/);
  const answerResponse = page.waitForResponse(response => response.url().endsWith('/api/agent/query'), { timeout: 360000 });
  await page.getByRole('button', { name: 'Agent 조회', exact: true }).click();
  const response = await answerResponse; const answer = await response.json();
  assert.equal(response.status(), 200, JSON.stringify(answer));
  await page.getByTestId('agent-answer').waitFor();
  assert.match(answer.answer, /°C/); assert.ok(answer.answer.includes(registry.equipment[3].primary_tag));
  const evidence = answer.evidence.find(item => item.field === '관측값');
  const trace = await json(`/api/agent/traces/${answer.trace_id}`);
  let source = trace.calls.find(call => call.id === evidence.tool_id).result;
  for (const part of evidence.path) source = source[part];
  assert.equal(source, evidence.value); assert.equal(evidence.unit, '°C');
  await page.getByText('조회 근거·도구 기록 보기', { exact: true }).click();
  await page.getByText(`기록 ID ${answer.trace_id}`, { exact: true }).waitFor();
  await page.getByText('조회 근거·도구 기록 보기', { exact: true }).click();
  const traceUrl = `**/api/agent/traces/${answer.trace_id}`;
  await page.route(traceUrl, route => route.abort('failed'));
  await page.getByText('조회 근거·도구 기록 보기', { exact: true }).click();
  await drawer.getByRole('alert').waitFor();
  await page.unroute(traceUrl);
  await drawer.getByRole('button', { name: '다시 조회', exact: true }).click();
  await page.getByText(`기록 ID ${answer.trace_id}`, { exact: true }).waitFor();
  await page.locator('#monitoring').scrollIntoViewIfNeeded();
  await page.screenshot({ path: resolve(out, 'ai-drawer.jpg'), type: 'jpeg', quality: 82 });
  writeFileSync(resolve(out, 'agent-answer.json'), JSON.stringify({ answer, trace }, null, 2));
  pass('Drawer preserves questions across tabs, accepts spaces, and displays real Ollama answer with verified °C and in-page trace');

  await page.getByRole('tab', { name: '승인 연습', exact: true }).click();
  const proposalResponse = page.waitForResponse(response => response.url().endsWith('/api/simulator/proposals'), { timeout: 360000 });
  await page.getByRole('button', { name: 'Agent Simulator 제안 생성', exact: true }).click();
  const proposed = await proposalResponse; const proposal = await proposed.json();
  assert.equal(proposed.status(), 200, JSON.stringify(proposal)); assert.equal(proposal.requested_value, 1);
  await poll(async () => await page.getByTestId('proposal-status').textContent() === 'pending', 'Proposal ready');
  assert.equal(await page.getByRole('button', { name: '승인 및 Simulator 실행', exact: true }).isDisabled(), true);
  await page.getByRole('checkbox').check(); await page.getByRole('button', { name: '승인 및 Simulator 실행', exact: true }).click();
  await poll(async () => await page.getByTestId('proposal-status').textContent() === 'executed', 'Explicit approval');
  assert.equal(await page.getByTestId('sim-value').textContent(), '1');
  await page.screenshot({ path: resolve(out, 'simulator-drawer.jpg'), type: 'jpeg', quality: 82 });
  await page.getByRole('button', { name: '승인·변경 기록 보기', exact: true }).click();
  await page.getByRole('heading', { name: '변경 실행', exact: true }).waitFor();
  await page.route('**/api/simulator/audit?*', route => route.abort('failed'));
  await page.getByRole('button', { name: '기록 새로고침', exact: true }).click();
  await drawer.getByRole('alert').waitFor();
  await page.unroute('**/api/simulator/audit?*');
  await drawer.getByRole('button', { name: '다시 조회', exact: true }).click();
  await drawer.getByRole('alert').waitFor({ state: 'hidden' });
  assert.equal(context.pages().length, initialPages); assert.deepEqual(downloads, []);
  await page.screenshot({ path: resolve(out, 'audit-drawer.jpg'), type: 'jpeg', quality: 82 });
  const audit = await json('/api/simulator/audit');
  assert.ok(audit.some(row => row.event === 'executed' && row.proposal_id === proposal.id));
  writeFileSync(resolve(out, 'simulator-audit.json'), JSON.stringify(audit, null, 2));
  pass('Real model proposal and explicit approval execute once; audit is readable in the same drawer without new tabs or downloads');
  pass('Empty audit is explained; injected Trace/Audit network failures show errors and recover by retrying the real endpoints');

  await page.getByRole('tab', { name: 'AI 질문', exact: true }).click();
  let release;
  let intercepted;
  const arrived = new Promise(resolve => { intercepted = resolve; });
  const gate = new Promise(resolve => { release = resolve; });
  const lateRoute = async route => { intercepted(); await gate; await route.fulfill({ json: answer }).catch(() => {}); };
  await page.route('**/api/agent/query', lateRoute);
  await page.getByRole('button', { name: 'Agent 조회', exact: true }).click();
  await arrived;
  await page.getByLabel('선택 센서', { exact: true }).selectOption(registry.equipment[0].primary_tag);
  release();
  await page.unrouteAll({ behavior: 'wait' });
  assert.equal(await page.getByTestId('agent-answer').count(), 0);
  await page.getByRole('tab', { name: '승인 연습', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Agent Simulator 제안 생성', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: '재열기 선택하고 AI 질문으로 이동', exact: true }).click();
  assert.equal(await selected(), registry.equipment[3].primary_tag);
  assert.equal(await page.getByRole('tab', { name: 'AI 질문', exact: true }).evaluate(node => node === document.activeElement), true);
  await page.getByRole('tab', { name: 'AI 질문', exact: true }).focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: '승인 연습', exact: true }).getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Escape'); await drawer.waitFor({ state: 'hidden' });
  pass('Sensor change cancels a held response and clears prior answer/evidence; preparation shortcut, keyboard tabs and Escape work');

  await page.getByRole('link', { name: '운전 분석', exact: true }).click();
  await poll(async () => (await page.locator('.workspace-header').boundingBox()).y >= -1, 'Sticky header');
  assert.ok((await page.locator('#analysis').boundingBox()).y >= (await page.locator('.workspace-header').boundingBox()).height - 2, 'Anchor is not behind sticky header');
  await page.getByRole('link', { name: '모니터링', exact: true }).click();
  await page.getByRole('button', { name: '04 재열기', exact: true }).click();
  await page.getByRole('tab', { name: '센서 상세', exact: true }).click();
  await inspect(page, 'workspace-desktop', out);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: resolve(out, 'workspace-desktop.jpg'), type: 'jpeg', quality: 82 });
  for (const width of [1280, 900, 768, 375, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await inspect(page, `workspace-${width}`, out);
    assert.equal(await drawer.evaluate(node => node.scrollWidth > node.clientWidth + 1), false);
  }
  await page.screenshot({ path: resolve(out, 'workspace-mobile.jpg'), type: 'jpeg', quality: 82 });
  pass('Sticky menu and unobscured anchors; drawer and named controls fit 1800/1280/900/768/375/320px');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '메뉴', exact: true }).focus();
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'true');
  await page.getByRole('button', { name: 'AI 질문', exact: true }).press('Enter');
  await drawer.waitFor();
  await page.getByRole('tab', { name: '센서 상세', exact: true }).press('Home');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: '메뉴', exact: true }).evaluate(node => node === document.activeElement), true);
  await page.getByRole('button', { name: '02 화로', exact: true }).focus();
  await page.keyboard.press('Space');
  assert.equal(await selected(), registry.equipment[1].primary_tag);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: '02 화로', exact: true }).evaluate(node => node === document.activeElement), true);
  const canvas = page.locator('canvas');
  await canvas.evaluate(node => node.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
  await page.getByText('3D VIEW UNAVAILABLE').waitFor();
  await page.getByRole('button', { name: '04 재열기', exact: true }).click();
  assert.equal(await selected(), registry.equipment[3].primary_tag);
  pass('Mobile menu and equipment work with Space/Enter; Escape restores focus; WebGL context loss retains sensor selection');
}
